def build_matrix_report(user: dict) -> list[str]:
    """Independent valid Telegram HTML chunks, each strictly under 3900 chars."""
    matrix, sections = report_sections(user)
    blocks = []
    for section in sections:
        blocks.append(f"<b>{escape(section['title'])}</b>\n{escape(section['intro'])}")
        blocks.extend(section["blocks"])
    chunks, current = [], ""
    for block in blocks:
        if len(block) > 3700:
            raise ValueError("Раздел разбора превышает размер сообщения")
        candidate = current + ("\n\n" if current else "") + block
        if len(candidate) > 3700:
            chunks.append(current)
            current = block
        else:
            current = candidate
    if current:
        chunks.append(current)
    date_label = parse_birth_date(matrix["birth_date"]).strftime("%d.%m.%Y")
    return [f"<b>Твоя матрица · {date_label} · {index}/{len(chunks)}</b>\n\n{chunk}"
            for index, chunk in enumerate(chunks, 1)]


