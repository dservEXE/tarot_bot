def _position_block(node):
    key, value = node["id"], node["value"]
    card = INTERPRETATIONS[value]
    heading = f"{key} · {node['title']} — {value}, {ARCANA[value]}"
    group = node["group"]
    domain = "family" if group == "family" else "money" if group == "money" else "love" if group == "love" else None
    context = f"В этой позиции полезно {card[domain]}." if domain else f"Попробуй: {card['step']}."
    return (f"<b>{escape(heading)}</b>\n{escape(POSITION_FOCUS[key])}\n"
            f"Ресурс: {escape(card['resource'])}. Риск: {escape(card['challenge'])}.\n"
            f"{escape(context)}")


